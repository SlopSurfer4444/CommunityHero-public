// Finite R3 workload: production App writers, isolated PG fixtures and private
// CAS only. Set both explicitly named fixture URLs/databases before selecting.
fn r3_workload_parity(left:Value,right:Value){
    // Shared comparator now proves BOTH original receipt/archive hashes before
    // canonicalizing generated UUIDs. Do not overwrite either original digest.
    logical_eq(left,right);
}
fn r3_numeric_metrics(events:&[Value],scoped:bool)->Value{
    let stage=if scoped{"preparation.projection.materialized"}else{"workspace.projection.materialized"};
    let materialized:Vec<_>=events.iter().filter(|e|e["stage"]==stage).collect();
    assert_eq!(materialized.len(),1,"one actual reducer projection per measured writer");
    let held=if scoped{"preparation.final.writer.held"}else{"workspace.writer.held"};
    let held:Vec<_>=events.iter().filter(|e|e["stage"]==held).collect();assert_eq!(held.len(),1);
    let calls=|stage:&str|events.iter().filter(|e|e["stage"]==stage).count();
    let controls:Vec<_>=events.iter().filter(|e|e["stage"]=="r3.scope.controls.materialized").map(|e|e["work"].clone()).collect();
    assert!(calls("r3.sql.read")>0,"actual SQL probe must be integrated");
    json!({"materialized":materialized[0]["work"],"controls":controls,"sqlReads":calls("r3.sql.read"),
        "sqlWrites":calls("r3.sql.write"),"writerHeldMs":held[0]["elapsedMs"],
        "sqlScope":"successful application statements; excludes SQLx BEGIN/COMMIT/connection initialization",
        "byteScope":"raw selected PG JSON text plus metadata; controls separate; not physical TOAST/index/bloat"})
}
