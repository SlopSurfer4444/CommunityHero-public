    let (replay,changed)=db.change_preparation_final(&run,Intent::Recovery{plan:&plan,profile:&profile,at:&at},None).await.unwrap();
    assert!(!changed);assert_eq!(replay,outcome);assert_eq!(db.read().await.unwrap(),approved);
    // The legacy running reservation is last: its synthetic row and captured
    // bundle stay durable, with no deletion, cancellation or reset cleanup.
    let (mut reserved,reserved_run,reserved_profile,reserved_plan,_)=fixture_named(automatic,&format!("r9-final-{automatic}-reservation-"));
    let mut clean=db.read().await.unwrap();merge_final_scenario(&mut clean,reserved.clone());let at=crate::now();
