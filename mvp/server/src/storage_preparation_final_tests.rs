fn replace_generated_refs(value:&mut Value,ids:&std::collections::HashMap<String,String>){match value{
    Value::Object(object)=>for value in object.values_mut(){replace_generated_refs(value,ids);},
    Value::Array(array)=>for value in array{replace_generated_refs(value,ids);},
    Value::String(s)=>if let Some(id)=ids.get(s){*s=id.clone();},_=>(),
}}
fn final_value_hash(value:&Value)->String{
    use sha2::{Digest,Sha256};format!("{:x}",Sha256::digest(value.to_string().as_bytes()))
}
fn logical_eq(a:Value,b:Value){logical_eq_from(None,a,b);}
fn logical_eq_from(initial:Option<&Value>,a:Value,mut b:Value){
    // Verify each ORIGINAL document before canonicalizing generated output.
    // A wrong receipt/archive hash cannot be repaired by this comparison.
    for document in [&a,&b]{
        for job in crate::list(document,"jobs"){
            if !job["completedRecovery"].is_null(){
                assert_eq!(job["completedRecovery"]["version"],1);
                assert_eq!(job["status"],"completed");assert_eq!(job["result"],job["prepareOutcome"]);
                assert_eq!(job["completedRecovery"]["outcomeDigest"],final_value_hash(&job["prepareOutcome"]));
            }
        }
        for archive in document["preparationResearch"].as_array().into_iter().flatten(){
            if archive.get("checksum").is_some(){
                assert_eq!(archive["checksum"],crate::research_cache::checksum(archive));
            }
        }
    }
    // The existing engine reducer samples its review time internally. Normalize
    // only its generated archive/review clock, after proving those exact clocks
    // and review bodies belong to the same job. Source chronology is untouched.
    for (index,left) in a["preparationResearch"].as_array().into_iter().flatten().enumerate(){
        let right=&b["preparationResearch"][index];
        if left["createdAt"]!=right["createdAt"]{
            let run=left["jobId"].as_str().unwrap();
            let original=initial.expect("Clock normalization requires the original workspace");
            let old_job=crate::row(original,"jobs",run).unwrap();
            assert!(old_job["completedRecovery"].is_null());assert!(old_job["preparationStages"]["review"].is_null());
            assert!(!original["preparationResearch"].as_array().into_iter().flatten()
                .any(|archive|archive["id"]==left["id"]||archive["jobId"]==run),"Retained archive chronology is immutable");
            assert_eq!(right["jobId"],run);assert_eq!(left["id"],format!("research:{run}"));assert_eq!(left["id"],right["id"]);
            for (document,archive) in [(&a,left),(&b,right)]{
                let job=crate::row(document,"jobs",run).unwrap();
                assert_eq!(job["purpose"],"engine_prepare");assert!(job["completedRecovery"].is_object());
                assert_eq!(archive["checksum"],crate::research_cache::checksum(archive));
                assert_eq!(archive["review"],job["preparationStages"]["review"]);
                assert_eq!(archive["createdAt"],archive["review"]["at"]);
                chrono::DateTime::parse_from_rfc3339(archive["createdAt"].as_str().unwrap()).unwrap();
            }
            let at=left["createdAt"].clone();
            b["preparationResearch"][index]["createdAt"]=at.clone();
            b["preparationResearch"][index]["review"]["at"]=at.clone();
            crate::row_mut(&mut b,"jobs",run).unwrap()["preparationStages"]["review"]["at"]=at;
        }
    }
    // Only the new proposal/audit identities generated by paired reducers may
    // differ. Map by ordered output rows, preserving all references and their
    // relationships; a dangling/wrong reference cannot receive a mapping.
    let mut ids=std::collections::HashMap::new();
    for table in ["proposals","audit"]{
        assert_eq!(crate::list(&a,table).len(),crate::list(&b,table).len(),"{table}");
        for (index,left) in crate::list(&a,table).iter().enumerate(){
            let right=&mut b[table][index];
            if left["id"]!=right["id"]{
                let old=right["id"].as_str().unwrap();let expected=left["id"].as_str().unwrap();
                assert!(uuid::Uuid::parse_str(old).is_ok()&&uuid::Uuid::parse_str(expected).is_ok());
                assert!(ids.insert(old.to_owned(),expected.to_owned()).is_none());
                right["createdAt"]=left["createdAt"].clone();
            }
        }
    }
    replace_generated_refs(&mut b,&ids);
    // Derived hashes were verified against original bytes above. Recompute only
    // after deterministic identity/clock canonicalization for exact comparison.
    for job in b["jobs"].as_array_mut().unwrap(){
        if !job["completedRecovery"].is_null(){
            job["completedRecovery"]["outcomeDigest"]=json!(final_value_hash(&job["prepareOutcome"]));
        }
    }
    for archive in b.get_mut("preparationResearch").and_then(Value::as_array_mut).into_iter().flatten(){
        if archive.get("checksum").is_some(){archive["checksum"]=json!(crate::research_cache::checksum(archive));}
    }
    assert_eq!(a,b);
}
fn preserve(before:&Value,after:&Value,recovery:bool){
    for key in ["approvals","operations","feedback","conversations","posts","branches","materials","knowledge_entries","knowledge_versions"]{
        assert_eq!(before[key],after[key],"{key}");
    }
    assert_eq!(crate::row(before,"jobs","old-paid").unwrap(),crate::row(after,"jobs","old-paid").unwrap());
    let old=crate::list(before,"audit");let new=crate::list(after,"audit");
    assert!(new.starts_with(old));assert_eq!(new.len(),old.len()+usize::from(recovery));
}
fn assert_legacy_local_recovery(before:&Value,after:&Value,run:&str){
    let original=crate::row(before,"jobs",run).unwrap();
    let groups=original["preparationStages"]["groupAdmission"].as_array().unwrap();
    assert!(!groups.is_empty());assert!(groups.iter().all(|group|group["status"]=="pending"));
    assert!(crate::list(before,"proposals").iter().all(|p|p["prepareRunId"]!=run),"no original proposals for this pending capture");
    assert_ne!(original["prepareBundle"]["request"]["mandatoryMaterialContract"],crate::preparation_materials::CONTRACT,"genuine historical captured request");
    let created=crate::list(after,"proposals").iter().filter(|p|p["prepareRunId"]==run).collect::<Vec<_>>();
    assert!(!created.is_empty(),"reducer reached actual local proposal recovery");
    for proposal in created{
        assert_eq!(proposal["status"],"draft");
        assert_eq!(crate::proposal_current(after,proposal).unwrap_err().1,"legacy_material_contract_unmet","local recovery does not acquire new publication authority");
    }
    assert_eq!(after["approvals"],before["approvals"]);assert_eq!(after["operations"],before["operations"]);
    assert_eq!(crate::row(after,"jobs",run).unwrap()["prepareBundle"],original["prepareBundle"],"original capture bytes remain fixed");
    assert_eq!(crate::row(after,"jobs",run).unwrap()["preparationStages"]["first"],original["preparationStages"]["first"]);
}
fn simulate_scoped(initial:&Value,run:&str,intent:&Intent<'_>)->ApiResult<(Value,Value)>{
    let before=final_projection(initial,run)?;let mut after=before.clone();
    let (outcome,receipt)=intent.apply(&mut after,run)?;
    validate_final(&before,&after,run,intent.recovery())?;
    validate_audit_output(&before,&after,run,intent.recovery(),receipt.as_ref())?;
    let mut merged=initial.clone();merge_final(&mut merged,&before,&after,receipt.as_ref())?;
    Ok((merged,outcome))
}

